DROP TABLE IF EXISTS ESERCIZI;
DROP TABLE IF EXISTS PROGRAMMI_REST;

CREATE TABLE PROGRAMMI_REST (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(64) NOT NULL UNIQUE,
    kcal INT NOT NULL
);

CREATE TABLE ESERCIZI (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idProgramma BIGINT NOT NULL,
    nomeEs     VARCHAR(64) NOT NULL,
    numSerie   INT   NOT NULL,
    numRep     INT   NOT NULL,
    kcal       FLOAT NOT NULL,

    FOREIGN KEY (idProgramma) REFERENCES PROGRAMMI_REST(id) ON DELETE CASCADE
)


